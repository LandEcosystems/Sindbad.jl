using Sindbad
using Statistics: mean
# StaticArray/SVector are reexported by SindbadTEM (hence by Sindbad) -- no separate import needed.

# Regenerates SindbadTEM's process/approach test data from a real run of this directory's
# own setup (its forcing.json is purpose-built to cover every approach's forcing needs, and its
# model_structure.json is a real, working model structure -- not tied to any one specific
# example experiment like WROASTED).
#
#   - tmp_forcing: one location's forcing, averaged over the whole loaded period for
#     time-varying variables (rather than pinned to one arbitrary day's snapshot).
#   - tmp_helpers: from Sindbad.Simulation.getRunTEMInfo(info, forcing) -- the (dates, run,
#     numbers, pools) shape `helpers` has everywhere else.
#   - land + reference_approaches: see the "sequential test harness" section below.
#
# Run with: julia --project=tools/benchmark/TestSindbadTEM tools/benchmark/TestSindbadTEM/derive_sindbadTEM_test_data.jl
#
# Needs this directory's own Project.toml (not the repo root's, and not SindbadTEM's) -- it pins
# HTTP.jl to 1.x, same fix and reason as examples/scripts/Project.toml: Zarr.jl's HTTPStore
# forces the OpenSSL TLS backend via a `socket_type_tls` kwarg that only HTTP.jl's 1.x client
# honors; HTTP 2.x silently ignores it and fails the TLS handshake against the sindbad S3 bucket
# forcing.json's data_path points at.

experiment_json = joinpath(@__DIR__, "experiment.json")

info = getExperimentInfo(experiment_json);
forcing = getForcing(info);
# getRunTEMInfo's return isn't itself what gets passed as `helpers` to define/precompute/compute
# -- that's its nested .model_helpers (SindbadTEM/src/Methods.jl calls Processes.define(model,
# forcing, land, model_helpers), where model_helpers = getRunTEMInfo(...).model_helpers).
tmp_helpers = Sindbad.Simulation.getRunTEMInfo(info, forcing).model_helpers;

# ForcingWithTime variables (daily time series) get averaged over the whole loaded period;
# ForcingWithoutTime ones (soil properties, PFT, ...) are already a single constant per site.
tmp_forcing_pairs = map(enumerate(forcing.f_types)) do (f_index, f)
    f_name, f_type = first(f), last(f)
    f_value = forcing.data[f_index]
    nameof(typeof(f_type)) == :ForcingWithTime ? Pair(f_name, mean(f_value)) : (size(f_value)[1] == 1 ? Pair(f_name, f_value[1]) : Pair(f_name, f_value))
end
tmp_forcing = (; tmp_forcing_pairs...)

# --------------------------------------------------------------------------------------
# Serialize each NamedTuple as valid, re-parseable Julia source (not `repr`, which would
# silently turn SVector pools into plain Vector literals and lose the type).
# --------------------------------------------------------------------------------------
juliaLiteral(x::AbstractFloat) = repr(x)
juliaLiteral(x::Integer) = repr(x)
juliaLiteral(x::Symbol) = repr(x)
juliaLiteral(x::AbstractString) = repr(x)
juliaLiteral(x::Nothing) = "nothing"

function juliaLiteral(x::StaticArray)
    # Tuple-argument form: StaticArraysCore alone (no full StaticArrays) only defines the
    # SArray{S,T,N,L}(::NTuple{L,T}) constructor, not the varargs sugar SVector(a, b, c...).
    elems = join(juliaLiteral.(x), ", ")
    return "SVector{$(length(x)),$(eltype(x))}(($elems,))"
end

function juliaLiteral(x::AbstractVector)
    elems = join(juliaLiteral.(x), ", ")
    return "$(eltype(x))[$elems]"
end

function juliaLiteral(x::Tuple)
    elems = join(juliaLiteral.(x), ", ")
    return length(x) == 1 ? "($elems,)" : "($elems)"
end

function juliaLiteral(x::NamedTuple)
    isempty(x) && return "NamedTuple()"
    entries = join(("$(k) = $(juliaLiteral(v))" for (k, v) in pairs(x)), ",\n    ")
    return "(;\n    $entries\n)"
end

# `land.models.*` holds instantiated approach structs (e.g. wCycleBase_simple(), the
# soil-hydraulics sub-model used by drainage/groundwater approaches). @with_kw overrides
# `show` with a non-reparseable field-dump, so these need an explicit constructor-call form.
function juliaLiteral(x::LandEcosystem)
    T = typeof(x)
    fields = fieldnames(T)
    isempty(fields) && return "$(T)()"
    kwargs = join(("$(f) = $(juliaLiteral(getfield(x, f)))" for f in fields), ", ")
    return "$(T)(; $kwargs)"
end

juliaLiteral(x) = repr(x)  # fallback for anything else (e.g. Dict, Dates.Date/DateTime)

function writeTestData(path, varname, value)
    open(path, "w") do io
        println(io, "# AUTO-GENERATED by tools/benchmark/TestSindbadTEM/derive_sindbadTEM_test_data.jl -- do not hand-edit.")
        println(io, "# Regenerate with: julia --project=. tools/benchmark/TestSindbadTEM/derive_sindbadTEM_test_data.jl")
        println(io)
        println(io, "using SindbadTEM")
        println(io, "using StaticArrays: SVector")
        println(io, "using Dates")
        println(io)
        println(io, "$varname = $(juliaLiteral(value))")
    end
    @info "Wrote $varname" path
end

test_data_dir = joinpath(@__DIR__, "..", "..", "..", "SindbadTEM", "test", "test_data")
mkpath(test_data_dir)

# --------------------------------------------------------------------------------------
# land + reference approaches, for the sequential test harness (checkApproaches.jl).
#
# The real flow (runTEMOne -> definePrecomputeTEM then computeTEM, SindbadTEM/src/Methods.jl)
# is: for each process in the selected model structure, in order: define, then precompute
# (thread land through all of them) -- THEN, in a separate pass: for each process in the same
# order: compute (thread land through all of them again). So the correct input for testing one
# approach is this minimal, initial land (nothing computed yet) built up through the *actual
# upstream sequence* of processes before it, using a reference approach per process -- not a
# static, already-fully-populated land.
#
# info.helpers.land_init doesn't carry a placeholder namespace (land.LAI, land.cAllocation, ...)
# for every process in standard_sindbad_model unless the model structure selects all of them --
# every missing one gets an empty NamedTuple added here.
# --------------------------------------------------------------------------------------
land_raw = info.helpers.land_init
missing_process_fields = [p => NamedTuple() for p in standard_sindbad_model if !hasproperty(land_raw, p)]
land = (; pairs(land_raw)..., missing_process_fields...)

# The reference approach set is exactly this experiment's own model structure selection
# (TestSindbadTEM/model_structure.json -- a real, working, internally-consistent set of models) --
# nothing invented for processes it doesn't select; checkApproaches.jl just doesn't advance `land`
# for those (see its own comments). Add more models to model_structure.json (and rerun this
# script) to extend coverage over time, the same way new forcing variables get added to
# forcing.json.
reference_approaches = nameof.(typeof.(info.models.forward))

writeTestData(joinpath(test_data_dir, "forcing.jl"), "tmp_forcing", tmp_forcing)
writeTestData(joinpath(test_data_dir, "helpers.jl"), "tmp_helpers", tmp_helpers)
writeTestData(joinpath(test_data_dir, "land.jl"), "land", land)
writeTestData(joinpath(test_data_dir, "referenceApproaches.jl"), "reference_approaches", reference_approaches)
