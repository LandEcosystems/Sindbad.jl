# `Base.FieldError` (a structured exception for "type X has no field Y", thrown by
# `@unpack_nt`/property access on a NamedTuple) only exists from Julia 1.12 -- this package
# supports 1.10-1.12 (see SindbadTEM/Project.toml's `[compat] julia`). Pre-1.12, the same failure
# is a plain `ErrorException` with the same message text, so that's the fallback detection. Same
# check as SindbadTEM/test/checkApproaches.jl's `isMissingFieldError` -- duplicated here rather
# than shared since these are two separate standalone scripts.
const _HAS_FIELD_ERROR = isdefined(Base, :FieldError)
function isMissingFieldError(e)
    _HAS_FIELD_ERROR && return e isa Base.FieldError
    return e isa ErrorException && occursin("has no field", e.msg)
end

function leafSubtypes(T)
    subs = subtypes(T)
    isempty(subs) && return [T]
    return reduce(vcat, (isabstracttype(S) ? leafSubtypes(S) : [S] for S in subs))
end

# Returns dotted-path strings (e.g. "fluxes.sublimation") naming every NaN/Inf leaf, so a
# report can say exactly which variable is wrong instead of just how many.
function findInvalidNumbers(x, path=Symbol[])
    invalid = Vector{String}()
    _collectInvalid!(invalid, x, path)
    return invalid
end
_collectInvalid!(invalid, x::AbstractFloat, path) = (isfinite(x) || push!(invalid, join(path, ".")); nothing)
function _collectInvalid!(invalid, x::Union{NamedTuple,Tuple}, path)
    foreach(pairs(x)) do (k, v)
        _collectInvalid!(invalid, v, k isa Symbol ? [path; k] : path)
    end
end
_collectInvalid!(invalid, x::AbstractArray, path) = foreach(v -> _collectInvalid!(invalid, v, path), x)
_collectInvalid!(invalid, x, path) = nothing

# A raw `FieldError` message on a NamedTuple never says *which* NamedTuple was missing the
# field (forcing? land.pools? helpers?) -- but the message lists every field that NamedTuple
# *does* have, and that field set is unique per test-data NamedTuple. Walk every nested NamedTuple
# in the test data once to build a fieldset -> source registry, then match a caught error's
# "available fields" list against it.
function registerSource!(registry, fields, label::String)
    isempty(fields) && return  # ambiguous either way (many process placeholders start empty)
    push!(get!(registry, Set{Symbol}(fields), String[]), label)
end

function collectNamedTupleRegistry!(registry, x, path)
    if x isa NamedTuple
        registerSource!(registry, Set(keys(x)), path)
        for (k, v) in pairs(x)
            collectNamedTupleRegistry!(registry, v, isempty(path) ? string(k) : path * "." * string(k))
        end
    end
end

function matchFieldErrorSource(errmsg, registry)
    m = match(r"available fields:\s*(.+)$", errmsg)
    m === nothing && return nothing
    avail = Set(Symbol(String(mm.captures[1])) for mm in eachmatch(r"`([^`]+)`", m.captures[1]))
    isempty(avail) && return nothing
    return get(registry, avail, nothing)
end

nt_registry = Dict{Set{Symbol},Vector{String}}()
collectNamedTupleRegistry!(nt_registry, tmp_forcing, "forcing")
collectNamedTupleRegistry!(nt_registry, land, "land")
collectNamedTupleRegistry!(nt_registry, tmp_helpers, "helpers")

# A FieldError on an approach STRUCT is a different situation entirely: the type name is
# already right there in the message (`type evaporation_Snyder2000 has no field ...`), so
# there's no ambiguity to resolve about *which* struct -- what's actually useful is knowing
# *whose* parameter that missing field is. This is exactly the "shared update/define method on
# the abstract process type hardcodes `@unpack_$OneSpecificApproach params`, but params is a
# DIFFERENT approach" bug pattern (see e.g. evaporation.jl's `update`, which always does
# `@unpack_evaporation_bareFraction params` regardless of which evaporation_* was actually
# passed in). `getInOutModel(model, :parameters)` gives each approach's own field names.
field_owner = Dict{Symbol,Vector{String}}()
for T in leafSubtypes(LandEcosystem)
    params_io = getInOutModel(T(), :parameters)  # Vector of fieldname => description Pairs
    for (fn, _) in params_io
        push!(get!(field_owner, fn, String[]), string(nameof(T)))
    end
end

function formatSourceLabel(sources)
    length(sources) == 1 && return sources[1]
    return "possibly: " * join(sources, ", ")
end

function formatError(e)
    msg = sprint(showerror, e)
    m_type = match(r"type (\S+) has no field `([^`]+)`", msg)
    if m_type !== nothing && m_type.captures[1] != "NamedTuple"
        field = Symbol(m_type.captures[2])
        owners = get(field_owner, field, nothing)
        owners === nothing || return "[likely wrong-approach parameters -- `$field` belongs to: $(formatSourceLabel(owners))] " * msg
    end
    sources = matchFieldErrorSource(msg, nt_registry)
    return sources === nothing ? msg : "[$(formatSourceLabel(sources))] " * msg
end

# The first stack frame inside SindbadTEM/src/Processes/ -- i.e. where SINDBAD's own code (the
# approach itself, or a shared helper it called like landUtils.jl) actually broke, as opposed to
# deep in Base/StaticArrays internals. Trimmed to a repo-relative path so it reads sensibly
# regardless of the checkout location (local machine vs. CI runner).
function firstSindbadFrame(bt)
    for frame in stacktrace(bt)
        file = string(frame.file)
        idx = findfirst("SindbadTEM/src/Processes", file)
        idx === nothing || return "$(file[first(idx):end]):$(frame.line)"
    end
    return ""
end

# `severity` mirrors checkApproaches.jl's `outcomeFromException`: a missing-field error means
# this test's reference selection doesn't cover some *other* upstream process the approach under
# test needs (or a structural mismatch like a fixed soil-layer-count guard) -- `:incompatible`,
# not a bug. Anything else (UndefVarError, MethodError, a plain `error()` guard, ...) reflects the
# approach's own code and is a genuine `:bug`. Empty string for non-error statuses (ok/
# invalid_number/not_defined), where severity doesn't apply.
# `stage` distinguishes a failure in the compute-chain's own define/precompute prerequisite
# re-run (see runComputePhase) from a failure in the method actually under test -- without it, a
# bug in an approach's `define` shows up as TWO identical-looking "error" rows (one for `define`
# itself, one for `compute`, since testing `compute` chains through this same approach's own
# `define`+`precompute` first), misleading anyone triaging the report into thinking there are two
# separate bugs to find instead of one.
function errorResult(e, land; stage=nothing)
    severity = isMissingFieldError(e) ? "incompatible" : "bug"
    msg = formatError(e)
    stage === nothing || (msg = "[same root cause as this approach's own \"$stage\" row above] " * msg)
    return (; status="error", severity, errmsg=msg, location=firstSindbadFrame(catch_backtrace()),
        time_ms=NaN, bytes=-1, n_allocs=-1, invalid_paths=String[], result=land)
end

# Cold call (JIT-compiles + allocates whatever the method itself allocates) is discarded as a
# warm-up; the measured call reuses the identical input so it hits the already-compiled
# specialization -- otherwise every measurement would mostly be reporting JIT overhead, not the
# approach's actual behavior. `define` allocates for real (it's creating pools/arrays); a
# well-written `precompute`/`compute` should allocate ~0 once warm.
function measureCall(f, params, forcing, land, helpers)
    try
        f(params, forcing, land, helpers)  # warm-up, discarded
    catch e
        return errorResult(e, land)
    end
    try
        local land2
        t0 = time_ns()
        bytes = @allocated (land2 = f(params, forcing, land, helpers))
        time_ms = (time_ns() - t0) / 1e6
        n_allocs = @allocations f(params, forcing, land, helpers)  # separate call, same (warm) input
        invalid_paths = unique(findInvalidNumbers(land2))
        status = isempty(invalid_paths) ? "ok" : "invalid_number"
        return (; status, severity="", errmsg="", location="", time_ms, bytes, n_allocs, invalid_paths, result=land2)
    catch e
        return errorResult(e, land)
    end
end

function measureMethod(f, mname, params, forcing, land, helpers)
    io = getInOutModel(params, mname)
    defined = !(isempty(io[:input]) && isempty(io[:output]))
    defined || return (; status="not_defined", severity="", errmsg="", location="", time_ms=NaN, bytes=-1, n_allocs=-1, invalid_paths=String[], result=land)
    return measureCall(f, params, forcing, land, helpers)
end

_selected_by_process = let selected = Dict{Symbol,Any}()
    for name in reference_approaches
        T = getfield(SM, name)
        selected[nameof(supertype(T))] = T
    end
    selected
end
reference_sequence = map(SM.standard_sindbad_model) do p
    (; process=p, process_type=getfield(SM, p), ref_type=get(_selected_by_process, p, nothing))
end

results = NamedTuple[]
function recordResult!(results, process_name, approach_name, method_name, m)
    push!(results, (; process=process_name, approach=approach_name, method=method_name,
        status=m.status, severity=m.severity, time_ms=m.time_ms, bytes=m.bytes, n_allocs=m.n_allocs,
        invalid_paths=m.invalid_paths, location=m.location, errmsg=m.errmsg))
end

# Each phase is wrapped in a function (rather than reassigning `land` in a top-level `for` loop)
# to avoid Julia's top-level "soft scope" ambiguity, where an assignment to an existing global
# from inside a `for` loop silently creates a new loop-local shadow instead of updating it.

# The reference approach for a process comes from a real experiment's own model structure (see
# the module-level comment above), so it should always succeed -- but a process
# `reference_approaches` doesn't cover has `ref_type === nothing`, and if the reference approach
# nonetheless errors against this test's specific forcing/helpers, `land` is left unchanged for
# that step (a warning is logged) rather than aborting the whole sequential chain -- downstream
# processes just won't see that one process's contribution, same as a true no-op.
function advanceReference(f, ref_type, forcing, land, helpers, step_label)
    ref_type === nothing && return land
    try
        return f(ref_type(), forcing, land, helpers)
    catch e
        @warn "Reference approach failed while advancing the sequential chain; leaving `land` unchanged for this step" step = step_label ref = ref_type exception = e
        return land
    end
end

function runDefinePrecomputePhase(results, land0)
    land = land0
    for step in reference_sequence
        process_name = string(step.process)
        for T in leafSubtypes(step.process_type)
            approach_name = string(nameof(T))
            params = T()
            m_define = measureMethod(SM.define, :define, params, tmp_forcing, land, tmp_helpers)
            recordResult!(results, process_name, approach_name, "define", m_define)
            m_precompute = measureMethod(SM.precompute, :precompute, params, tmp_forcing, m_define.result, tmp_helpers)
            recordResult!(results, process_name, approach_name, "precompute", m_precompute)
        end
        land = advanceReference(SM.define, step.ref_type, tmp_forcing, land, tmp_helpers, (step.process, :define))
        land = advanceReference(SM.precompute, step.ref_type, tmp_forcing, land, tmp_helpers, (step.process, :precompute))
    end
    return land
end

# Chains T's own define+precompute on top of the upstream `land` (built by earlier processes'
# reference chain) so compute is measured against exactly what T's own precompute would hand it
# in a real run -- not the reference approach's define/precompute output for this same process
# slot. An approach that caches something in its own process's land namespace during
# define/precompute and reads it back in compute (a normal pattern, e.g. cAllocationSoilW_gppGSI's
# c_allocation_f_soilW_prev) would otherwise be measured against the wrong land and fail on a
# missing field that has nothing to do with a real bug.
#
# The define/precompute re-run is caught separately from the actual `compute` call (rather than
# one `try`/`catch` around all three) so a bug in `define` -- already its own row from
# runDefinePrecomputePhase -- gets tagged as such here too, instead of being indistinguishable
# from a genuine `compute` bug (see errorResult's `stage` argument).
function chainedComputeResult(params, forcing, land, helpers)
    defined = try
        SM.define(params, forcing, deepcopy(land), helpers)
    catch e
        return errorResult(e, land; stage="define")
    end
    land_for_compute = try
        SM.precompute(params, forcing, defined, helpers)
    catch e
        return errorResult(e, land; stage="precompute")
    end
    return measureMethod(SM.compute, :compute, params, forcing, land_for_compute, helpers)
end

function runComputePhase(results, land0)
    land = land0
    for step in reference_sequence
        process_name = string(step.process)
        for T in leafSubtypes(step.process_type)
            approach_name = string(nameof(T))
            params = T()
            m_compute = chainedComputeResult(params, tmp_forcing, land, tmp_helpers)
            recordResult!(results, process_name, approach_name, "compute", m_compute)
        end
        land = advanceReference(SM.compute, step.ref_type, tmp_forcing, land, tmp_helpers, (step.process, :compute))
    end
    return land
end

land_after_definePrecompute = runDefinePrecomputePhase(results, deepcopy(land))
land_after_compute = runComputePhase(results, deepcopy(land_after_definePrecompute))

# `update` is a separate, optional per-timestep path (only invoked when `inline_update` is set),
# not part of the base define/precompute/compute pipeline -- tested independently per approach
# against the fully-built final land state, not chained. Most approaches don't override it, so
# measuring it by default is mostly noise -- opt in with SINDBADTEM_BENCHMARK_METHODS, matching
# checkApproaches.jl's own default-off `functions` option for the same reason.
benchmark_methods = Set(Symbol.(split(get(ENV, "SINDBADTEM_BENCHMARK_METHODS", "define,precompute,compute"), ",")))
if :update in benchmark_methods
    for T in leafSubtypes(LandEcosystem)
        process_name = string(nameof(supertype(T)))
        approach_name = string(nameof(T))
        m_update = measureMethod(SM.update, :update, T(), tmp_forcing, land_after_compute, tmp_helpers)
        recordResult!(results, process_name, approach_name, "update", m_update)
    end
end

# Pipe-delimited output (invalid_paths itself ";"-joined, since a cell can have several bad
# variables) -- avoids adding a CSV/JSON dependency just for this report.
out_path = length(ARGS) >= 1 ? ARGS[1] : joinpath(@__DIR__, "benchmark_output", "benchmark_results.psv")
mkpath(dirname(out_path))
open(out_path, "w") do io
    println(io, "process|approach|method|defined|status|severity|time_ms|bytes|n_allocs|invalid_paths|location|errmsg")
    for r in results
        errmsg_1line = replace(r.errmsg, "\n" => " / ")
        invalid_joined = join(r.invalid_paths, ";")
        defined = r.status != "not_defined"
        println(io, join((r.process, r.approach, r.method, defined, r.status, r.severity,
                r.time_ms, r.bytes, r.n_allocs, invalid_joined, r.location, errmsg_1line), "|"))
    end
end
println("Wrote ", length(results), " rows to ", out_path)
