# Measures every approach's define/precompute/compute (update is opt-in, off by default -- see
# SINDBADTEM_BENCHMARK_METHODS below) and writes a pipe-delimited report of
# status/time/allocations/invalid-variables/error per method-call. Pairs with
# renderBenchmarkReport.jl, which turns this into a browsable HTML table.
#
# Real SINDBAD runs (runTEMOne -> definePrecomputeTEM, then computeTEM; see
# SindbadTEM/src/Methods.jl) call every process's `define`+`precompute` in sequence first
# (threading `land` through all of them), and only *then*, in a separate pass, call `compute`
# for every process in the same order. A single static `land` input is not what any approach
# actually sees -- it's the land some *other* upstream choice of approaches would have produced.
# So instead: replay the real sequence with a reference approach per process (`reference_approaches`,
# generated by derive_sindbadTEM_test_data.jl straight from a real experiment's own
# `info.models.forward` -- an actual, internally-consistent model structure, not an arbitrary
# per-process fallback), and at each slot ALSO measure every one of that process's approaches
# against the same, correctly-built-up upstream `land` -- without letting the tested approach's
# own output feed forward (only the reference approach's output advances the chain). A process
# `reference_approaches` doesn't cover simply doesn't advance `land` for that step (see
# `advanceReference`).
#
# Run with: julia --project=SindbadTEM tools/benchmark/TestSindbadTEM/benchmarkApproaches.jl [output.psv]

test_data_dir = joinpath(@__DIR__, "..", "..", "..", "SindbadTEM", "test", "test_data")
include(joinpath(test_data_dir, "forcing.jl"))
include(joinpath(test_data_dir, "land.jl"))
